  # 这几类**不可能**是我们的买家，列表里默认折叠起来（只是不显示，不删不改）。
  #
  # 收得很克制：只放行业代码认得死死、且业务上没有例外的。
  # ⚠️「广告代理」「管理咨询」故意不收——Sport Signage 的 NAICS 是 541810 广告代理，
  # 但它是做赛事标识的，真有可能买屏。折错一条真线索的代价，比多看几条噪音大。
  NOT_BUYERS = %w[报纸出版 期刊出版 出版 广播电视 影视制作
                  职业介绍 劳务派遣 人力服务
                  行业协会 政府机构 银行 保险 律所].freeze

  def self.not_buyer?(label) = label.present? && NOT_BUYERS.include?(label)

  # 一家公司常挂好几个代码，取能匹配到的里面**最细**的那个。
  def self.for(codes)
    Array(codes).filter_map { |code| match(code.to_s) }
                .max_by { |_label, length| length }&.first
  end

  # ⚠️ 取前缀的长度不能超过代码本身——'54161' 取前 6 位还是它自己，
  # 却会被当成「匹配了 6 位」，把真正更细的 '561311' 比下去（g2 Recruitment
  # 因此被归成管理咨询而不是职业介绍）。
  def self.match(code)
    code.length.downto(2) do |n|
      label = LABELS[code[0, n]]
      return [label, n] if label
    end
    nil
  end
  private_class_method :match
end
